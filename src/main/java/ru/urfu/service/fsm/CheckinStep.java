package ru.urfu.service.fsm;

/**
 * Шаги диалога чекина, которые проходит пользователь по порядку.
 */
public enum CheckinStep {
    /**
     * Ожидание оценки настроения от 1 до 10.
     */
    SCORE,
    /**
     * Ожидание заметки или команды /skip.
     */
    NOTE,
    /**
     * Показ карточки и ожидание подтверждения /approve.
     */
    PREVIEW
}
